import { Card, cardType } from "../Card";
import { createEffect, EffectDefinition } from "../effects/effect";

export function createCard(id: MinionId): Card {
  const minion = minions.find((minion) => minion.id === id);
  if (!minion) throw new Error("Could not find the minion id in minions");
  return new Card(
    minion.name,
    minion.attack,
    minion.health,
    minion.description,
    minion.imageKey,
    minion.effects.map((e) => createEffect(e)),
    minion.type,
    minion.cost,
    minion.tier,
    minion.value,
  );
}
export function createEnemy(id: EnemyId): Card {
  const minion = enemies.find((minion) => minion.id === id);
  if (!minion) throw new Error("Could not find the boss id in bosses");
  return new Card(
    minion.name,
    minion.attack,
    minion.health,
    minion.description,
    minion.imageKey,
    minion.effects.map((e) => createEffect(e)),
    minion.type,
    minion.cost,
    minion.tier,
    minion.value,
  );
}

